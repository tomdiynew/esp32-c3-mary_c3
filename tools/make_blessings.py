"""Generate main/blessings.h: the blessings shown on every 10th flower, and a KaiTi glyph set (with outline) for them.
Also writes art/blessings.txt for reading.

Each glyph pixel is one byte: high nibble = outline coverage (glyph grown by STROKE px), low nibble = fill coverage.

    python tools/make_blessings.py
"""
import pathlib

from PIL import Image, ImageDraw, ImageFont

FONT = r"C:\Windows\Fonts\STKAITI.TTF"
SIZE = 26
STROKE = 2
ADVANCE = 29
MAX_CHARS = 7
ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "main" / "blessings.h"
TXT = ROOT / "art" / "blessings.txt"

BLESSINGS = [
    "万福玛利亚", "圣母护佑", "愿主赐福", "平安喜乐", "蒙恩蒙福", "爱与希望同在", "心存感恩", "喜乐常在",
    "愿你被爱包围", "恩典满满", "信望爱常存", "心灵平安", "花开满心", "愿你心想事成", "光明常伴", "圣母垂怜",
    "福杯满溢", "温柔而坚定", "岁月静好", "一切都会好起来", "愿你健康平安", "家庭和睦", "好运连连", "天天好心情",
    "心有繁花", "善良被温柔以待", "感恩每一天", "所求皆如愿", "前路光明", "万事顺意",
]


def glyph(font, ch):
    cell = SIZE + 4 * STROKE
    ascent, _ = font.getmetrics()
    pos = (cell // 2, 2 * STROKE + ascent)
    fill = Image.new("L", (cell, cell), 0)
    outline = Image.new("L", (cell, cell), 0)
    ImageDraw.Draw(fill).text(pos, ch, fill=255, font=font, anchor="ms")
    ImageDraw.Draw(outline).text(pos, ch, fill=255, font=font, anchor="ms", stroke_width=STROKE, stroke_fill=255)
    x0, y0, x1, y1 = outline.getbbox()
    f, o = fill.load(), outline.load()
    data = bytes(min(15, (o[x, y] + 8) // 17) << 4 | min(15, (f[x, y] + 8) // 17)
                 for y in range(y0, y1) for x in range(x0, x1))
    return x1 - x0, y1 - y0, x0 - cell // 2, y0, data


def main():
    for b in BLESSINGS:
        assert 2 <= len(b) <= MAX_CHARS, b
    assert len(set(BLESSINGS)) == len(BLESSINGS)
    chars = sorted({c for b in BLESSINGS for c in b})
    assert len(chars) <= 255
    index = {c: i for i, c in enumerate(chars)}
    font = ImageFont.truetype(FONT, SIZE)
    bits, table = bytearray(), []
    for c in chars:
        w, h, x, y, data = glyph(font, c)
        table.append((len(bits), w, h, x, y, c))
        bits += data

    L = ["/* Generated by tools/make_blessings.py - do not edit. */", "#pragma once", "", "#include <stdint.h>", "",
         f"#define BLESSING_COUNT   {len(BLESSINGS)}", f"#define BLESSING_MAX     {MAX_CHARS}",
         f"#define BLESSING_ADVANCE {ADVANCE}", f"#define BLESSING_CELL_H  {SIZE + 4 * STROKE}",
         f"#define BLESSING_INK_MID {(min(t[4] for t in table) + max(t[4] + t[2] for t in table)) // 2}"
         "  // ink center, from the cell top", "",
         "typedef struct {",
         "    uint32_t off;   // into s_bless_bits: w*h bytes, high nibble outline, low nibble fill",
         "    uint8_t  w, h;",
         "    int8_t   x;     // from the center of the character cell",
         "    int8_t   y;     // from the top of the character cell",
         "} bless_glyph_t;", "",
         f"/* {pathlib.Path(FONT).name} {SIZE} px + {STROKE} px outline, {len(chars)} characters, {len(bits)} bytes */",
         "static const uint8_t s_bless_bits[] = {"]
    for i in range(0, len(bits), 32):
        L.append("    " + ",".join(f"0x{b:02X}" for b in bits[i:i + 32]) + ",")
    L += ["};", "", f"static const bless_glyph_t s_bless_glyphs[{len(chars)}] = {{"]
    L += [f"    {{{off}, {w}, {h}, {x}, {y}}},  // {c}" for off, w, h, x, y, c in table]
    L += ["};", "", "/* glyph indices, 0xFF = end */", "static const uint8_t s_blessings[BLESSING_COUNT][BLESSING_MAX + 1] = {"]
    for b in BLESSINGS:
        idx = [index[c] for c in b] + [0xFF] * (MAX_CHARS + 1 - len(b))
        L.append("    {" + ", ".join(f"{i:3d}" for i in idx) + f"}},  // {b}")
    L += ["};", ""]
    OUT.write_text("\n".join(L), encoding="utf-8", newline="\n")
    TXT.write_text("圣母献花：每献满 10 朵随机显示其中一句（修改请改 tools/make_blessings.py 后重新生成）\n\n"
                   + "\n".join(f"{i + 1:2d}. {b}" for i, b in enumerate(BLESSINGS)) + "\n", encoding="utf-8-sig")
    print(f"{OUT.name}: {len(BLESSINGS)} blessings, {len(chars)} glyphs, {len(bits)} bytes")


if __name__ == "__main__":
    main()
